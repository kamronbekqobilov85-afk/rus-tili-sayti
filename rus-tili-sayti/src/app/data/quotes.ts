export function quoteOfTheDay(now: number = Date.now()): Quote {
  const TASHKENT_OFFSET_MS = 5 * 60 * 60 * 1000;
  const dayNumber = Math.floor((now + TASHKENT_OFFSET_MS) / 86_400_000);
  return quotes[dayNumber % quotes.length];
}
